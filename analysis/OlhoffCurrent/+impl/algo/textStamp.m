function I = textStamp(I, row, col, txt, scale)
%TEXTSTAMP  Burn a short ASCII label into a grayscale image using a built-in
%   5x7 bitmap font (no toolbox dependency).
if nargin < 5, scale = 3; end
G = charBitmaps();
x = col;
for c = txt
    key = upper(c);
    if isKey(G, key), B = G(key); else, B = zeros(7,5); end
    B = repelem(B, scale, scale);
    [h,w] = size(B);
    if row+h-1 <= size(I,1) && x+w-1 <= size(I,2)
        patch = I(row:row+h-1, x:x+w-1);
        patch(B>0) = 0;
        I(row:row+h-1, x:x+w-1) = patch;
    end
    x = x + w + scale;
end
end

