function sweep_lp()
%SWEEP_LP  The LP inner solve costs one linprog per outer iteration, so the
%   small move limits that the fixed-step outer loop needs become affordable.
%   The move limit is the ONLY step control in the paper's scheme -- there is no
%   damping -- so the terminal limit cycle has amplitude ~move.  Sweep it.
combos = { ...
   0.0200, 0.05,  400; ...
   0.0100, 0.05,  800; ...
   0.0050, 0.05, 1600; ...
   0.0020, 0.05, 3000; ...
   0.0010, 0.05, 4000; ...
   0.0050, 0.02, 1600; ...
   0.0050, 0.10, 1600; ...
   0.0020, 0.02, 3000};
fprintf('%-8s %-8s %-7s %8s %8s %8s %8s %7s %7s %6s\n', ...
        'move','tolMult','maxOut','omega1','omega2','omega3','gap','Mnd','bimod%','secs');
for i = 1:size(combos,1)
    mv = combos{i,1}; tm = combos{i,2}; mo = combos{i,3};
    cfg = defaultCfg();
    cfg.move=mv; cfg.tolMult=tm; cfg.maxOuter=mo; cfg.verbose=false;
    cfg.innerSolver='lp'; cfg.offDiag=false;
    res = olhoffOpt(cfg);
    h = res.hist; n = res.nOuter;
    last = max(1,n-49):n;
    gap = (res.omega(2)-res.omega(1))/res.omega(1);
    Mnd = sum(4*res.rho.*(1-res.rho))/numel(res.rho);
    fprintf('%-8.4f %-8.3f %-7d %8.2f %8.2f %8.2f %8.4f %7.3f %7.0f %6.1f\n', ...
        mv,tm,mo,res.omega(1),res.omega(2),res.omega(3),gap,Mnd, ...
        100*mean(h.N(last)>=2), res.wallclock);
    save(sprintf('results/lp_mv%g_tm%g.mat',mv,tm),'res','-v7.3');
end
fprintf('\nTarget: omega1 = omega2 = 174.7 (bimodal), omega3 = 284.9\n');
end
