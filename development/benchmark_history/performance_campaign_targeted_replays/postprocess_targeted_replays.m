    'displacement_fraction_solid','kinetic_fraction_low','kinetic_fraction_gray','kinetic_fraction_solid', ...
    'strain_fraction_low','strain_fraction_gray','strain_fraction_solid','density_weighted_by_displacement', ...
    'peak_to_median_element_displacement','participation_elements_90pct'});
writetable(LM,fullfile(here,'proposed_160_mode_localization.csv'));

fig=figure('Visible','off','Color','w','Position',[50 50 1200 650]);plot(a.info.freq_iter_omega(:,1:3),'LineWidth',1.1); ...
    grid on;xlabel('iteration');ylabel('native \omega [rad/s]');legend('\omega_1','\omega_2','\omega_3','Location','best'); ...
    title('Proposed 160x20: retained native spectral history (diagnostic eigensolves)');
