function cfg = study_base_config(method, nelx, nely, params)
%STUDY_BASE_CONFIG Fully explicit configuration for the three-method study.

% This constructor is deliberately independent of the legacy performance JSON.
% It serializes effective native settings and never enables plotting or I/O in
% the timed optimization loops.

if nargin < 4, params = struct(); end
method = lower(char(method));

cfg = struct();
cfg.meta = struct('name', sprintf('three-method study %s %dx%d', method, nelx, nely));
cfg.benchmark = struct( ...
    'enable_diagnostics', logical(opt(params, 'enable_diagnostics', false)), ...
    'record_history', logical(opt(params, 'record_history', true)), ...
    'extend_beyond_native_stop', logical(opt(params, 'extend_beyond_native_stop', false)));
cfg.domain = struct( ...
    'shape', 'rectangular', ...
    'size', struct('length', 8.0, 'height', 1.0), ...
    'thickness', 1.0, ...
    'mesh', struct('nelx', nelx, 'nely', nely));
cfg.material = struct('model', 'plane_stress_isotropic', 'E', 1.0e7, 'nu', 0.3, 'rho', 1.0);
cfg.bc = struct('supports', [ ...
    struct('type', 'closest_point', 'location', [0.0, 0.5], 'dofs', {{'ux','uy'}}), ...
    struct('type', 'closest_point', 'location', [8.0, 0.5], 'dofs', {{'ux','uy'}})]);
cfg.postprocessing = struct( ...
    'visualize_live', false, ...
    'visualize_quality', 'regular', ...
    'visualize_modes', struct('enabled', false, 'count', 3), ...
    'visualize_topology_modes', struct('enabled', false, 'count', 3), ...
    'write_correlation_table', false, ...
    'save_snapshot_image', false, ...
    'save_final_image', false, ...
    'save_frequency_iterations', false);

switch method
    case 'yuksel'
        cfg.void_material = struct('E_min_ratio', 1.0e-9, 'rho_min', 1.0e-9);
        cfg.optimization = common_optimization('Yuksel', params, 0.2, 1000, 0.01, 2.5);
        cfg.optimization.optimizer = 'OC';
        % stage1_budget_independent defaults false, so the effective Stage-1
        % budget is unchanged for every existing caller.  Only a fixed-horizon
        % timing replay, whose max_iters is a Stage-2 horizon rather than a
        % global budget, sets it true.
        cfg.optimization.yuksel = struct( ...
            'stage1_max_iters', round(opt(params, 'stage1_max_iters', 1000)), ...
            'stage1_tol', opt(params, 'stage1_tol', 0.01), ...
            'stage2_tol', opt(params, 'stage2_tol', 0.01), ...
            'stage1_budget_independent', ...
                logical(opt(params, 'stage1_budget_independent', false)));

    case 'proposed'
        cfg.void_material = struct('E_min_ratio', 1.0e-9, 'rho_min', 1.0e-9);
        cfg.optimization = common_optimization('ourApproach', params, 0.2, 2000, 0.001, 2.0);
        cfg.optimization.optimizer = 'OC';
        cfg.optimization.semi_harmonic_baseline = 'solid';
        cfg.optimization.semi_harmonic_load_sensitivity = false;
        cfg.optimization.harmonic_normalize = false;
        if logical(opt(params, 'debug_formula', false))
            cfg.optimization.debug_semi_harmonic = true;
        end
        load = struct('type', 'semi_harmonic', 'mode', 1, 'factor', 1.0);
        cfg.domain.load_cases = struct('name', 'proposed_mode1', 'factor', 1.0, 'loads', load);

    otherwise
        error('study_base_config:UnknownMethod', 'Unknown method %s.', method);
end
end

function out = common_optimization(approach, params, move0, maxit0, tol0, rmin0)
out = struct( ...
    'approach', approach, ...
    'optimizer', 'OC', ...
    'objective', 'compliance', ...
    'interpolation', 'SIMP', ...
    'volume_fraction', 0.5, ...
    'penalization', 3.0, ...
    'filter', struct( ...
        'type', 'sensitivity', ...
        'heaviside', false, ...
        'radius', opt(params, 'rmin_element', rmin0), ...
        'radius_units', 'element', ...
        'boundary_condition', 'symmetric'), ...
    'move_limit', opt(params, 'move', move0), ...
    'max_iters', round(opt(params, 'max_iters', maxit0)), ...
    'convergence_tol', opt(params, 'tol', tol0));
end

function value = opt(s, name, default)
if isfield(s, name) && ~isempty(s.(name))
    value = s.(name);
else
    value = default;
end
end
