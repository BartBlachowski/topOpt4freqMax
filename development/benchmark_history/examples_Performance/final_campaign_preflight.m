function gate = final_campaign_preflight(resolutions, outputDir)
%FINAL_CAMPAIGN_PREFLIGHT No-solve, fail-closed final campaign admission gate.

here = fileparts(mfilename('fullpath'));
repo = fileparts(fileparts(here));
audit = fullfile(repo, 'analysis', 'olhoff_stabilization_audit');
study = fullfile(repo, 'analysis', 'three_method_parametric_study');
addpath(here);
addpath(fullfile(repo, 'Matlab', 'reproduction2007', 'runner'));

campaignPath = fullfile(audit, 'final_campaign_profile.json');
selectedPath = fullfile(audit, 'selected_profile.json');
provenancePath = fullfile(audit, 'provenance.json');
freezePath = fullfile(study, 'results', 'profile_freeze_manifest.json');
campaign = jsondecode(fileread(campaignPath));
selected = jsondecode(fileread(selectedPath));
provenance = jsondecode(fileread(provenancePath));
freeze = jsondecode(fileread(freezePath));

expectedMeshes = double(campaign.mesh_sequence);
assert(isequal(double(resolutions), expectedMeshes), ...
    'final_campaign_preflight:ResolutionMismatch', ...
    'Active resolutions differ from final_campaign_profile.json.');
assert(campaign.threads_per_run == 1 && maxNumCompThreads == 1, ...
    'final_campaign_preflight:ThreadMismatch', ...
    'The final campaign requires exactly one MATLAB computation thread.');

checks = struct();
checks.campaign_manifest_hash = strcmp(file_sha256(campaignPath), ...
    provenance.deliverable_sha256.final_campaign_profile_json);
checks.selected_profile_hash = strcmp(file_sha256(selectedPath), ...
    provenance.deliverable_sha256.selected_profile_json);
checks.olhoff_wrapper_hash = strcmp(file_sha256(fullfile(audit, 'olhoffOptStabilized.m')), ...
    provenance.audit_implementation.olhoffOptStabilized_sha256);
checks.common_evaluator_hash = strcmp(file_sha256(fullfile(study, 'study_evaluate_design.m')), ...
    provenance.audit_implementation.common_R3_evaluator_sha256);
checks.profile_ids = strcmp(campaign.profiles.Olhoff.profile_id, selected.profile_id) && ...
    strcmp(campaign.profiles.Yuksel.profile_id, freeze.profiles.yuksel_practical.profile_id) && ...
    strcmp(campaign.profiles.Proposed.profile_id, freeze.profiles.proposed_practical.profile_id);
checks.olhoff_runner = strcmp(campaign.profiles.Olhoff.runner, ...
    'analysis/olhoff_stabilization_audit/run_stabilization_case.m');
checks.output_isolated = strcmp(outputDir, fullfile(here, 'final_campaign'));
checks.output_not_legacy = ~any(strcmp(outputDir, {here, ...
    fullfile(here, 'diagnostic_yuksel_table1'), fullfile(here, 'equivalence'), ...
    audit, study}));

cfgHashes = struct('Olhoff', {cell(size(resolutions,1),1)}, ...
    'Yuksel', {cell(size(resolutions,1),1)}, 'Proposed', {cell(size(resolutions,1),1)});
configPass = true;
for i = 1:size(resolutions, 1)
    nx = resolutions(i,1); ny = resolutions(i,2);
    [o, oid] = final_campaign_config('Olhoff', nx, ny, outputDir);
    [y, yid] = final_campaign_config('Yuksel', nx, ny, outputDir);
    [p, pid] = final_campaign_config('Proposed', nx, ny, outputDir);

    configPass = configPass && strcmp(oid, selected.profile_id) && ...
        strcmp(yid, freeze.profiles.yuksel_practical.profile_id) && ...
        strcmp(pid, freeze.profiles.proposed_practical.profile_id);
    configPass = configPass && strcmp(o.optimization.approach, 'OlhoffStabilizedS1') && ...
        o.optimization.filter.radius == 1.3 && o.optimization.move_limit == 0.005 && ...
        o.optimization.max_iters == 1600 && ...
        o.optimization.stabilization.persistence == 100 && ...
        o.optimization.stabilization.move_stabilized == 0.0025 && ...
        o.optimization.stabilization.gap_threshold == 0.01 && ...
        o.optimization.stabilization.rmin_element == 1.3 && ...
        o.optimization.stabilization.max_iters_expected == 1600 && ...
        strcmp(o.optimization.stabilization.policy_id, 'S1') && ...
        ~o.optimization.stabilization.native_convergence_claim && ...
        o.optimization.rho_min == 0.001 && o.optimization.tol_mult == 0.05 && ...
        strcmpi(o.optimization.inner_solver, 'lp') && ~o.optimization.off_diagonal && ...
        strcmp(o.optimization.stabilization.output_dir, fullfile(outputDir, 'raw', 'olhoff')) && ...
        ~isfield(o.optimization, 'yuksel');
    configPass = configPass && strcmpi(y.optimization.approach, 'Yuksel') && ...
        strcmpi(y.optimization.optimizer, 'OC') && y.optimization.move_limit == 0.1 && ...
        y.optimization.filter.radius == 2.5 && y.optimization.max_iters == 1000 && ...
        y.optimization.yuksel.stage1_tol == 0.01 && y.optimization.yuksel.stage2_tol == 0.01;
    configPass = configPass && strcmpi(p.optimization.approach, 'ourApproach') && ...
        strcmpi(p.optimization.optimizer, 'OC') && p.optimization.move_limit == 0.2 && ...
        p.optimization.filter.radius == 2.0 && p.optimization.max_iters == 2000 && ...
        p.optimization.convergence_tol == 0.01 && ~p.optimization.harmonic_normalize;

    cfgHashes.Olhoff{i} = sha256_hex(jsonencode(orderfields(o)));
    cfgHashes.Yuksel{i} = sha256_hex(jsonencode(orderfields(y)));
    cfgHashes.Proposed{i} = sha256_hex(jsonencode(orderfields(p)));
end
checks.generated_configurations = configPass;

pathGuard = repro2007_paths(); %#ok<NASGU>
[baseCfg, ~] = repro2007_config('fig3a_best');
checks.olhoff_effective_boundary = baseCfg.rminEl == 1.3 && baseCfg.move == 0.005 && ...
    baseCfg.tolMult == 0.05 && baseCfg.rhomin == 0.001 && ...
    baseCfg.maxOuter == 1600 && baseCfg.threads == 1 && ...
    strcmpi(baseCfg.innerSolver, 'lp') && strcmpi(baseCfg.filterMode, 'diag') && ...
    ~baseCfg.offDiag;
checks.required_functions = exist('run_topopt_from_json', 'file') == 2 && ...
    exist('run_stabilization_case', 'file') == 2 && ...
    exist('olhoffOptStabilized', 'file') == 2 && ...
    exist('study_evaluate_design', 'file') == 2 && ...
    exist('final_campaign_run_case', 'file') == 2 && ...
    exist('final_campaign_config', 'file') == 2;

% The Olhoff column must NOT reach the optimizer through the legacy benchmark
% dispatcher.  That path carries the S0 / r_min = 2 profile, and the campaign
% would look identical while measuring a different method.
checks.olhoff_not_dispatched_legacy = ...
    ~strcmpi(campaign.profiles.Olhoff.profile_id, 'OlhoffDu2007Repro') && ...
    exist('run_stabilization_case', 'file') == 2;
checks.olhoff_work_semantics_labelled = ...
    contains(upper(campaign.profiles.Olhoff.work_semantics), 'NOT NATIVE CONVERGENCE') && ...
    ~selected.termination_and_work_semantics.native_convergence_claim && ...
    strcmp(campaign.profiles.Olhoff.successful_status, ...
           selected.termination_and_work_semantics.successful_row_status);
checks.status_precedence = isequal(cellstr(campaign.status_precedence(:)), ...
    {'SOLVER_FAILURE'; 'VALID_STABILIZED_STATE_AT_FIXED_WORK'; 'CAP_HIT'; 'RUNNING'});

vals = struct2cell(checks);
gate = struct();
gate.schema_version = '1.0';
gate.generated_without_optimization_solves = true;
gate.campaign_id = campaign.campaign_id;
gate.mesh_sequence = expectedMeshes;
gate.threads_per_run = campaign.threads_per_run;
gate.profile_ids = struct('Olhoff', campaign.profiles.Olhoff.profile_id, ...
    'Yuksel', campaign.profiles.Yuksel.profile_id, ...
    'Proposed', campaign.profiles.Proposed.profile_id);
gate.checks = checks;
gate.configuration_hashes = cfgHashes;
gate.output_dir = outputDir;
gate.pass = all(cellfun(@(x) islogical(x) && isscalar(x) && x, vals));
if ~gate.pass
    failed = fieldnames(checks);
    failed = failed(~cellfun(@(n) checks.(n), failed));
    error('final_campaign_preflight:Failed', ...
        'Final campaign preflight failed: %s', strjoin(failed, ', '));
end
fprintf('FINAL_CAMPAIGN_PREFLIGHT_PASS=1 (no optimization solves)\n');
end

function h = file_sha256(path)
fid = fopen(path, 'rb');
assert(fid >= 0, 'final_campaign_preflight:UnreadableFile', 'Cannot read %s.', path);
c = onCleanup(@() fclose(fid)); %#ok<NASGU>
bytes = fread(fid, Inf, '*uint8');
md = java.security.MessageDigest.getInstance('SHA-256');
if ~isempty(bytes), md.update(bytes); end
digest = typecast(md.digest(), 'uint8');
h = lower(reshape(dec2hex(digest, 2).', 1, []));
end
