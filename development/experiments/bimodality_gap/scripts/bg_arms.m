function A = bg_arms()
%BG_ARMS  Registry of the bimodality-gap experiment arms (single-factor interventions).
%
%   Baseline cells come from the recorded campaigns and are NOT re-run:
%     (Pedersen + linear mass, adaptive box)  examples/Performance/conference_benchmark/nine_mesh_pedersen_b21483b
%     (SIMP + eq.(4b) mass, beta-stall ladder) examples/Performance/conference_benchmark/campaign_9mesh_r2
%
%   Each arm below changes exactly ONE factor relative to a recorded baseline.
M4 = [160 20; 240 30; 320 40; 400 50];
M5 = [M4; 480 60];
A = struct('name', {}, 'preset', {}, 'overrides', {}, 'maxOuter', {}, 'meshes', {}, 'changes', {});

% material intervention at the FIXED adaptive-box controller (baseline: Pedersen preset)
A(end+1) = struct('name','simpAdaptive', 'preset','duOlhoffAdaptivePedersen', ...
    'overrides', {{'material.stiffness.model','simp', 'material.mass.model','eq4b'}}, ...
    'maxOuter', 400, 'meshes', M5, ...
    'changes', 'material law only: SIMP rho^3 + eq.(4b) mass instead of Pedersen + linear');

% controller intervention at the FIXED Pedersen material (baseline: SIMP ladder preset)
A(end+1) = struct('name','pedersenLadder', 'preset','duOlhoffFrozenM4', ...
    'overrides', {{'material.stiffness.model','pedersen', 'material.stiffness.linearBelow',0.1, 'material.mass.model','eq2'}}, ...
    'maxOuter', 400, 'meshes', M5, ...
    'changes', 'material law only: Pedersen + linear mass under the beta-stall ladder controller');

% filter radius fixed in ELEMENT units (3.0 el = the 400x50 physical value)
A(end+1) = struct('name','filterEl3', 'preset','duOlhoffAdaptivePedersen', ...
    'overrides', {{'filter.radiusPhysical',[], 'filter.radiusElements',3}}, ...
    'maxOuter', 400, 'meshes', M4, ...
    'changes', 'filter radius 3.0 elements at every mesh (physical R = 0.15, 0.10, 0.075, 0.06)');

% fixed iteration budget, no design-change stop (convergence-state control)
A(end+1) = struct('name','budget400', 'preset','duOlhoffAdaptivePedersen', ...
    'overrides', {{'stop.toleranceRule','explicit', 'stop.tolerance',0}}, ...
    'maxOuter', 400, 'meshes', [M4; 640 80; 800 100], ...
    'changes', 'stop disabled; 400 outer iterations at every mesh');

% physical filter radius doubled (interface-width intervention)
A(end+1) = struct('name','R012', 'preset','duOlhoffAdaptivePedersen', ...
    'overrides', {{'filter.radiusPhysical',0.12}}, ...
    'maxOuter', 400, 'meshes', M4, ...
    'changes', 'physical filter radius 0.12 instead of 0.06');

% per-element move-box ceiling doubled / halved (step-bound intervention on the trajectory)
A(end+1) = struct('name','box02', 'preset','duOlhoffAdaptivePedersen', ...
    'overrides', {{'move.initial',0.2}}, ...
    'maxOuter', 400, 'meshes', [160 20; 320 40; 400 50], ...
    'changes', 'adaptive box ceiling 0.20 instead of 0.10');
A(end+1) = struct('name','box005', 'preset','duOlhoffAdaptivePedersen', ...
    'overrides', {{'move.initial',0.05}}, ...
    'maxOuter', 400, 'meshes', [320 40; 400 50], ...
    'changes', 'adaptive box ceiling 0.05 instead of 0.10');
end
