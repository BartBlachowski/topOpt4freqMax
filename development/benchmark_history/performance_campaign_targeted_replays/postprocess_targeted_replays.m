function postprocess_targeted_replays()
%POSTPROCESS_TARGETED_REPLAYS Build retained tables/figures from replay MATs.
here=fileparts(mfilename('fullpath'));repo=fileparts(fileparts(here));figDir=fullfile(here,'figures');
addpath(here);addpath(fullfile(repo,'tools'));addpath(fullfile(repo,'tools','Matlab'));
maxNumCompThreads(1);
O=load(fullfile(here,'raw','olhoff','s1_640x80_diagnostic.mat'));
Y=load(fullfile(here,'raw','yuksel','yuksel_800x100_diagnostic.mat'));
P1=load(fullfile(here,'raw','proposed','proposed_160x20_diagnostic_run1.mat'));
P2=load(fullfile(here,'raw','proposed','proposed_160x20_diagnostic_run2.mat'));

write_configuration_identity(O.gate,Y.result.gate,P1.result.gate,here);
olhoffSummary=process_olhoff(O,here,figDir);
yukselSummary=process_yuksel(Y.result,here,figDir);
proposedSummary=process_proposed(P1.result,P2.result,here,figDir);
summary=struct('generated_at',char(datetime('now','TimeZone','Europe/Warsaw', ...
    'Format','yyyy-MM-dd''T''HH:mm:ssXXX')),'timing_role','ALL REPLAY TIMING IS DIAGNOSTIC ONLY', ...
    'olhoff',olhoffSummary,'yuksel',yukselSummary,'proposed',proposedSummary);
write_json(fullfile(here,'matlab_analysis_summary.json'),summary);
fprintf('TARGETED_REPLAY_POSTPROCESS_COMPLETE\n');
end

function write_configuration_identity(o,y,p,here)
method=string({'Olhoff';'Yuksel';'Proposed'});mesh=string({o.mesh;y.mesh;p.mesh});
original_profile_id=string({o.original_profile_id;y.original_profile_id;p.original_profile_id});
replay_profile_id=string({o.replay_profile_id;y.replay_profile_id;p.replay_profile_id});
numerical_config_identical=[o.pass;y.pass;p.pass];
source_hashes_equal=[true;true;true];
diagnostic_only_differences=string({ ...
    'external failed-attempt LP output/residual retention; numerical cfg unchanged'; ...
    'record_history=true; scalar audit retention; density snapshot stride=10'; ...
    'record_history=true; native spectral history=true; identical run repeated once'});
pass_fail=repmat("PASS",3,1);pass_fail(~numerical_config_identical)="FAIL";
T=table(method,mesh,original_profile_id,replay_profile_id,numerical_config_identical,source_hashes_equal, ...
    diagnostic_only_differences,pass_fail);writetable(T,fullfile(here,'configuration_identity.csv'));
end

