function gates = run_engineering_gates()
%RUN_ENGINEERING_GATES Validate executable identities before parameter sweeps.

repo = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(fullfile(repo, 'tools', 'Matlab'));
addpath(fullfile(repo, 'analysis', 'three_method_parametric_study'));
maxNumCompThreads(1);

gates = struct();
gates.timestamp = char(datetime('now','TimeZone','local','Format','yyyy-MM-dd''T''HH:mm:ssXXX'));
gates.matlab = version;
gates.thread_limit = maxNumCompThreads;

% Authoritative Proposed formula: the opt-in debug check independently
% reconstructs omega0^2*M(x)*Phi0 inside the solver and prints zero residual.
p = struct('max_iters', 2, 'record_history', true, ...
    'enable_diagnostics', true, 'debug_formula', true);
cfg = study_base_config('proposed', 40, 5, p);
[x1,w1,~,n1,~,~,t1] = run_topopt_from_json(cfg);
[x2,w2,~,n2,~,~,t2] = run_topopt_from_json(cfg);
gates.proposed_smoke = struct( ...
    'finite', all(isfinite([x1(:);w1(:)])), ...
    'iterations', n1, ...
    'deterministic_x_max_abs', max(abs(x1-x2)), ...
    'deterministic_omega_max_abs', max(abs(w1-w2)), ...
    'same_iteration_count', n1 == n2, ...
    'volume', mean(x1), ...
    'stop_status', t1.stopping.status);

% Fail-closed guards for the two non-native variants that must not enter the
% Proposed sweep under the native method name.
badBase = cfg;
badBase.optimization.semi_harmonic_baseline = 'initial';
gates.proposed_rejects_initial_reference = rejects(badBase, ...
    'topopt_freq:AuthoritativeBaselineRequired');
badSens = cfg;
badSens.optimization.semi_harmonic_load_sensitivity = true;
gates.proposed_rejects_load_sensitivity_variant = rejects(badSens, ...
    'topopt_freq:AuthoritativeLoadSensitivityOmitted');

% Yuksel smoke verifies stage accounting and finite two-stage output.
y = struct('max_iters', 3, 'stage1_max_iters', 3, 'record_history', true);
cfgY = study_base_config('yuksel', 40, 5, y);
[xy,wy,~,ny,~,nys,ty] = run_topopt_from_json(cfgY);
gates.yuksel_smoke = struct( ...
    'finite', all(isfinite([xy(:);wy(:)])), ...
    'stage1_iterations', nys.stage1, ...
    'stage2_iterations', nys.stage2, ...
    'total_iterations', ny, ...
    'iteration_identity', ny == nys.stage1 + nys.stage2, ...
    'time_identity_abs_error', abs(ty.yuksel.total_loop_time - ...
        (ty.yuksel.stage1_loop_time + ty.yuksel.stage2_loop_time)), ...
    'volume', mean(xy));

gates.pass = gates.proposed_smoke.finite && ...
    gates.proposed_smoke.deterministic_x_max_abs == 0 && ...
    gates.proposed_smoke.deterministic_omega_max_abs == 0 && ...
    gates.proposed_smoke.same_iteration_count && ...
    gates.proposed_rejects_initial_reference && ...
    gates.proposed_rejects_load_sensitivity_variant && ...
    gates.yuksel_smoke.finite && gates.yuksel_smoke.iteration_identity && ...
    gates.yuksel_smoke.time_identity_abs_error < 1e-10;

out = fullfile(repo, 'analysis', 'three_method_parametric_study', 'engineering_gates.json');
fid = fopen(out, 'w');
assert(fid >= 0, 'Unable to write %s', out);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '%s\n', jsonencode(gates, PrettyPrint=true));
fprintf('ENGINEERING_GATES_PASS=%d\n', gates.pass);
end

function tf = rejects(cfg, expectedId)
tf = false;
try
    run_topopt_from_json(cfg);
catch ME
    tf = strcmp(ME.identifier, expectedId);
end
end
