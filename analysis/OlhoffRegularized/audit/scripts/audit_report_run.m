function audit_report_run(tag)
%AUDIT_REPORT_RUN  Re-emit the AUDITRESULT summary line from a saved run.mat.
repo='/Users/piotrek/Programming/topOpt4freqMax';
d=fullfile(repo,'analysis','OlhoffRegularized','audit','results',tag);
L=load(fullfile(d,'run.mat'));h=L.hist;rho=L.rho;omega=L.omega;it=L.iterations;
cert=NaN;stat=NaN;
if isfield(h,'certificateSlope'),cert=h.certificateSlope(end);end
if isfield(h,'stationarityMeasure'),stat=h.stationarityMeasure(end);end
fprintf(['AUDITRESULT tag=%s status=%s stop=%s outer=%d accepted=%d rejected=%d ' ...
  'inner=%d contractions=%d w1=%.6f w2=%.6f w3=%.6f N=%d trust=%.3e ceil=%.3e ' ...
  'dxInf=%.3e dxRms=%.3e relObj=%.3e slope=%.3e cert=%.3e stat=%.3e vol=%.8f gray=%.4f wall=%.1f\n'], ...
  tag,L.status,L.stop_reason,it.outer,it.accepted_updates,it.rejected_trials, ...
  it.inner_total,it.move_ceiling_contractions,omega(1),omega(2),omega(3), ...
  h.N(end),h.trustNext(end),h.moveCeilingNext(end),h.densityChangeInf(end), ...
  h.densityChangeRms(end),h.relativeObjectiveChange(end),h.predictedSlope(end), ...
  cert,stat,mean(rho),4*mean(rho.*(1-rho)),L.meta.wall);
end
