function [cfg, profileId, profile] = final_campaign_config(method, nelx, nely, outputDir)
%FINAL_CAMPAIGN_CONFIG Build one frozen final-campaign method configuration.
%
% This constructor is the only configuration source used by the final campaign
% in performance_comparison.m.  It reads the authoritative campaign manifest
% and the already-frozen method profiles; it selects and tunes nothing.
%
%   analysis/olhoff_stabilization_audit/final_campaign_profile.json
%   analysis/olhoff_stabilization_audit/selected_profile.json
%   analysis/three_method_parametric_study/results/profile_freeze_manifest.json
%
% Every numeric setting below is READ from one of those three files.  Nothing
% is written here as a literal except the domain/mesh, which the campaign
% varies by design.
%
% See also FINAL_CAMPAIGN_PREFLIGHT, FINAL_CAMPAIGN_RUN_CASE.

here = fileparts(mfilename('fullpath'));
repo = fileparts(fileparts(here));
study = fullfile(repo, 'analysis', 'three_method_parametric_study');
audit = fullfile(repo, 'analysis', 'olhoff_stabilization_audit');
addpath(study);

campaign = jsondecode(fileread(fullfile(audit, 'final_campaign_profile.json')));
selected = jsondecode(fileread(fullfile(audit, 'selected_profile.json')));
freeze = jsondecode(fileread(fullfile(study, 'results', 'profile_freeze_manifest.json')));

method = char(string(method));
switch lower(method)
    case 'olhoff'
        profile = campaign.profiles.Olhoff;
        profileId = char(profile.profile_id);
        assert(strcmp(profileId, selected.profile_id), ...
            'final_campaign_config:OlhoffProfileMismatch', ...
            'Campaign and selected-profile Olhoff IDs differ.');

        nc = selected.normalized_configuration;
        trig = selected.stabilization_trigger;

        % The numeric gap threshold is DERIVED from the frozen condition
        % string, never restated here: if the manifest condition ever changes,
        % this stops matching rather than silently running the old number.
        tok = regexp(char(trig.condition), 'gap12\s*<=\s*([0-9.eE+-]+)', 'tokens', 'once');
        assert(~isempty(tok), 'final_campaign_config:OlhoffTriggerUnparsed', ...
            'Cannot read the gap threshold from the frozen condition "%s".', trig.condition);
        gapThreshold = str2double(tok{1});
        assert(isfinite(gapThreshold) && gapThreshold > 0, ...
            'final_campaign_config:OlhoffGapThreshold', ...
            'Parsed gap threshold %g is not usable.', gapThreshold);

        % The Olhoff column does NOT go through run_topopt_from_json.  Its
        % runner (run_stabilization_case) rebuilds repro2007_config('fig3a_best')
        % itself, so this struct is a declaration of what that runner must
        % produce -- checked at the optimizer boundary by
        % final_campaign_run_case -- plus the mesh and the output location.
        % It deliberately carries no Yuksel/ourApproach keys: a config object
        % archived in benchmark_results.json must not describe settings the
        % method never had.
        cfg = struct();
        cfg.meta = struct('name', sprintf('final campaign Olhoff %dx%d', nelx, nely));
        cfg.benchmark = struct('enable_diagnostics', false, 'record_history', false, ...
            'extend_beyond_native_stop', false);
        cfg.domain = struct( ...
            'shape', 'rectangular', ...
            'size', struct('length', 8.0, 'height', 1.0), ...
            'thickness', 1.0, ...
            'mesh', struct('nelx', nelx, 'nely', nely));
        cfg.optimization = struct( ...
            'approach', 'OlhoffStabilizedS1', ...
            'optimizer', 'LP', ...
            'objective', 'first_eigenfrequency', ...
            'interpolation', 'SIMP', ...
            'volume_fraction', 0.5, ...
            'filter', struct('type', 'sensitivity', 'radius', nc.rmin_element_widths, ...
                'radius_units', 'element', 'mode', char(nc.filter_mode)), ...
            'move_limit', nc.move_initial, ...
            'max_iters', nc.max_outer, ...
            'convergence_tol', NaN, ...
            'rho_min', nc.rho_min, ...
            'tol_mult', nc.tol_mult, ...
            'inner_solver', char(nc.inner_solver), ...
            'off_diagonal', logical(nc.off_diagonal));
        cfg.optimization.stabilization = struct( ...
            'profile_id', profileId, ...
            'base_factory', char(selected.base_factory), ...
            'runner', char(profile.runner), ...
            'policy_id', 'S1', ...
            'trigger_id', char(trig.id), ...
            'condition', char(trig.condition), ...
            'gap_threshold', gapThreshold, ...
            'persistence', trig.persistence_consecutive_iterations, ...
            'move_initial', nc.move_initial, ...
            'move_stabilized', nc.move_stabilized, ...
            'rmin_element', nc.rmin_element_widths, ...
            'max_iters_expected', nc.max_outer, ...
            'successful_status', char(profile.successful_status), ...
            'work_semantics', char(profile.work_semantics), ...
            'native_convergence_claim', ...
                logical(selected.termination_and_work_semantics.native_convergence_claim), ...
            'output_dir', fullfile(outputDir, 'raw', 'olhoff'));

    case 'yuksel'
        profile = campaign.profiles.Yuksel;
        profileId = char(profile.profile_id);
        frozen = freeze.profiles.yuksel_practical;
        assert(strcmp(profileId, frozen.profile_id), ...
            'final_campaign_config:YukselProfileMismatch', ...
            'Campaign and frozen Yuksel profile IDs differ.');
        prm = struct('move', frozen.move, 'rmin_element', frozen.rmin_element, ...
            'max_iters', frozen.max_iters, 'tol', frozen.stage2_tol, ...
            'stage1_tol', frozen.stage1_tol, 'stage2_tol', frozen.stage2_tol, ...
            'stage1_max_iters', frozen.max_iters, 'record_history', false);
        cfg = study_base_config('yuksel', nelx, nely, prm);

    case {'proposed', 'ourapproach'}
        profile = campaign.profiles.Proposed;
        profileId = char(profile.profile_id);
        frozen = freeze.profiles.proposed_practical;
        assert(strcmp(profileId, frozen.profile_id), ...
            'final_campaign_config:ProposedProfileMismatch', ...
            'Campaign and frozen Proposed profile IDs differ.');
        prm = struct('move', frozen.move, 'rmin_element', frozen.rmin_element, ...
            'max_iters', frozen.max_iters, 'tol', frozen.tol, ...
            'record_history', false);
        cfg = study_base_config('proposed', nelx, nely, prm);

    otherwise
        error('final_campaign_config:UnknownMethod', 'Unknown method "%s".', method);
end

cfg.meta.campaign_id = char(campaign.campaign_id);
cfg.meta.profile_id = profileId;
cfg.meta.work_semantics = char(profile.work_semantics);
cfg.meta.threads_per_run = campaign.threads_per_run;
cfg.postprocessing.visualize_live = false;
cfg.postprocessing.save_final_image = false;
cfg.postprocessing.save_snapshot_image = false;
end
