function smoke_branches()
%SMOKE_BRANCHES  Exercise every switchable branch for a few outer iterations so
%   that none of them is discovered broken later: filter mode, off-diagonal
%   switch (MMA vs the Krog & Olhoff LP route), element type, mass model.
variants = { ...
  'filter-diag',   struct('filterMode','diag'); ...
  'filter-all',    struct('filterMode','all'); ...
  'filter-none',   struct('filterMode','none'); ...
  'offdiag-off-LP',struct('offDiag',false); ...
  'elem-Q6',       struct('elemType','Q6'); ...
  'mass-4a',       struct('massInterp','4a'); ...
  'mass-4b',       struct('massInterp','4b'); ...
  'support-corner',struct('support','corner','axial','one'); ...
  'maximize-w2',   struct('n',2)};
fprintf('%-16s %9s %9s %9s %6s %8s %s\n','variant','omega1','omega2','omega3','N','cumInner','status');
for i = 1:size(variants,1)
    over = variants{i,2}; over.maxOuter = 6; over.verbose = false;
    try
        cfg = defaultCfg();
        fn = fieldnames(over); for k=1:numel(fn), cfg.(fn{k}) = over.(fn{k}); end
        res = olhoffOpt(cfg);
        fprintf('%-16s %9.2f %9.2f %9.2f %6d %8d %s\n', variants{i,1}, ...
            res.omega(1),res.omega(2),res.omega(3),res.hist.N(end), ...
            res.hist.cumInner(end),'ok');
    catch ME
        fprintf('%-16s %9s %9s %9s %6s %8s FAILED: %s\n', variants{i,1}, ...
            '-','-','-','-','-', ME.message);
    end
end
end
