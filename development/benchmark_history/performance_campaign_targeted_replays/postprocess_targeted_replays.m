function s=process_yuksel(r,here,figDir)
H=r.info.history;n=H.n;relativeObjectiveChange=NaN(n,1);
for k=2:n
    if H.stage(k)==H.stage(k-1),relativeObjectiveChange(k)=abs(H.objective(k)-H.objective(k-1))/max(abs(H.objective(k-1)),eps);end
end
stepP95=NaN(n,1);stepActiveFrac=stepP95;moveFrac=stepP95;modeCos=stepP95;modeAngleDeg=stepP95;du=stepP95;
snapshotChecksum=strings(n,1);snapshotTurnover=NaN(n,1);
[stepP95,stepActiveFrac,moveFrac,modeCos,modeAngleDeg,du,snapshotChecksum,snapshotTurnover]= ...
    add_yuksel_audit(r.info.stage1.audit,0,stepP95,stepActiveFrac,moveFrac,modeCos,modeAngleDeg,du, ...
    snapshotChecksum,snapshotTurnover);
[stepP95,stepActiveFrac,moveFrac,modeCos,modeAngleDeg,du,snapshotChecksum,snapshotTurnover]= ...
    add_yuksel_audit(r.info.stage2.audit,r.info.stage1.iterations,stepP95,stepActiveFrac,moveFrac,modeCos,modeAngleDeg,du, ...
    snapshotChecksum,snapshotTurnover);
dominantFractionUpperBound=NaN(n,1);dominantCountUpperBound=NaN(n,1);
localized=stepP95<0.5*H.d_inf_design;
dominantFractionUpperBound(localized)=0.05;dominantCountUpperBound(localized)=ceil(0.05*numel(r.xFinal));
T=table(H.iter,H.stage,H.stage_iter,H.d_inf_design,H.d_rms_design,H.d_inf,H.d_rms,H.objective, ...
    relativeObjectiveChange,H.rV,H.grayness,H.move_active_frac,stepP95,stepActiveFrac,moveFrac, ...
    modeCos,modeAngleDeg,du,dominantFractionUpperBound,dominantCountUpperBound, ...
    snapshotChecksum,snapshotTurnover, ...
    'VariableNames',{'total_iteration','stage','stage_iteration','max_dx','rms_dx', ...
    'max_dx_physical','rms_dx_physical','objective','relative_objective_change','relative_volume_residual', ...
    'grayness','move_active_fraction','step_p95','step_active_fraction','move_fraction', ...
    'mode_cosine','mode_angle_deg','mode_update_norm','dominant_fraction_upper_bound', ...
    'dominant_count_upper_bound','density_checksum_at_snapshot','binary_turnover_since_prior_snapshot'});
writetable(T,fullfile(here,'yuksel_800_history.csv'));

starts=[701 801 901 701];ends=[800 900 1000 1000];labels=string({'S2 701-800';'S2 801-900';'S2 901-1000';'S2 final 300'});
W=table('Size',[4 19],'VariableTypes',{'string','double','double','double','double','double','double','double', ...
    'double','double','double','double','double','double','double','string','string','string','string'}, ...
    'VariableNames',{'window','stage','global_start','global_end','max_dx_start','max_dx_end','max_dx_median', ...
    'rms_dx_median','max_to_rms_median','objective_relative_span','median_relative_objective_change', ...
    'median_step_p95_to_max','fraction_iterations_localized','max_snapshot_turnover', ...
    'dominant_variable_fraction_upper_bound','objective_frequency_trend','motion_pattern', ...
    'cap_classification','diagnosis'});
for i=1:4
    idx=r.info.stage1.iterations+(starts(i):ends(i));x=T.max_dx(idx);rr=T.rms_dx(idx);ob=T.objective(idx);
    W.window(i)=labels(i);W.stage(i)=2;W.global_start(i)=idx(1);W.global_end(i)=idx(end);W.max_dx_start(i)=x(1);W.max_dx_end(i)=x(end);
    W.max_dx_median(i)=median(x,'omitnan');W.rms_dx_median(i)=median(rr,'omitnan');
    W.max_to_rms_median(i)=median(x./max(rr,eps),'omitnan');
    W.objective_relative_span(i)=(max(ob)-min(ob))/max(abs(mean(ob)),eps);
    W.median_relative_objective_change(i)=median(T.relative_objective_change(idx),'omitnan');
    W.median_step_p95_to_max(i)=median(T.step_p95(idx)./max(x,eps),'omitnan');
    W.fraction_iterations_localized(i)=mean(localized(idx));
    W.max_snapshot_turnover(i)=max(T.binary_turnover_since_prior_snapshot(idx),[],'omitnan');
    W.dominant_variable_fraction_upper_bound(i)=0.05;
    W.objective_frequency_trend(i)="OBJECTIVE_STABLE; final native frequency only";
    W.motion_pattern(i)="IRREGULAR_OSCILLATION + LOCALIZED_VARIABLE_MOTION";
    W.cap_classification(i)="PERSISTENT_NONCONVERGENCE";
    W.diagnosis(i)="not a simple cap limitation; modest extension not justified";
end
writetable(W,fullfile(here,'yuksel_800_cap_diagnosis.csv'));

late=r.info.stage1.iterations+(701:1000);
fig=figure('Visible','off','Color','w','Position',[50 50 1200 650]);semilogy(T.total_iteration(late),T.max_dx(late),'LineWidth',1.2);hold on; ...
    semilogy(T.total_iteration(late),T.rms_dx(late),'LineWidth',1.2);yline(.01,'k--','native tolerance'); ...
    grid on;xlabel('total iteration');ylabel('density change');legend('max |dx|','RMS dx','Location','best'); ...
    title('Yuksel 800x100: final 300 Stage-2 iterations');
exportgraphics(fig,fullfile(figDir,'03_yuksel_800_late_density_change.png'),'Resolution',180);close(fig);
fig=figure('Visible','off','Color','w','Position',[50 50 1200 650]);yyaxis left;plot(T.total_iteration(late),T.objective(late),'LineWidth',1.2); ...
    ylabel('moving-load compliance');yyaxis right;semilogy(T.total_iteration(late),max(T.relative_objective_change(late),eps),'LineWidth',1.0); ...
    ylabel('relative objective change');xlabel('total iteration');grid on;title('Yuksel 800x100: late objective behavior');
exportgraphics(fig,fullfile(figDir,'04_yuksel_800_late_objective.png'),'Resolution',180);close(fig);

s=struct('status',r.status,'endpoint_matches_original',r.original_comparison.endpoint_matches_original, ...
    'total_iterations',r.info.timing.total_iterations,'stage1_iterations',r.info.stage1.iterations, ...
    'stage2_iterations',r.info.stage2.iterations,'final_max_dx',r.info.stopping.final_max_density_change, ...
    'final_rms_dx',r.info.stopping.final_rms_density_change,'final_relative_objective_change', ...
    r.info.stopping.final_relative_objective_change,'final_omega',r.omega(:).', ...
    'final_density_checksum',numeric_fingerprint(r.xFinal),'diagnostic_wall_time_s',r.diagnostic_wall_time_s, ...
    'late300_max_dx_min',min(T.max_dx(late)),'late300_max_dx_max',max(T.max_dx(late)), ...
    'late300_max_dx_median',median(T.max_dx(late)),'late300_rms_dx_median',median(T.rms_dx(late)), ...
    'late300_objective_relative_span',(max(T.objective(late))-min(T.objective(late)))/abs(mean(T.objective(late))), ...
    'late300_median_relative_objective_change',median(T.relative_objective_change(late),'omitnan'), ...
    'late300_fraction_localized_upper_bound',mean(localized(late)), ...
    'late300_median_p95_to_max',median(T.step_p95(late)./T.max_dx(late),'omitnan'));
end

function [p95,active,mv,mc,ma,du,checks,turn]=add_yuksel_audit(a,offset,p95,active,mv,mc,ma,du,checks,turn)
idx=offset+a.iter(:);p95(idx)=a.stepP95;active(idx)=a.stepActiveFrac;mv(idx)=a.moveFrac;
mc(idx)=a.modeCos;ma(idx)=a.modeAngleDeg;du(idx)=a.du;
prev=[];
for j=1:numel(a.snapshotIter)
    k=offset+a.snapshotIter(j);x=a.xPhysSnapshots(:,j);checks(k)=numeric_fingerprint(x);
    if ~isempty(prev),turn(k)=mean(binary_exact(x)~=binary_exact(prev));end;prev=x;
end
end

