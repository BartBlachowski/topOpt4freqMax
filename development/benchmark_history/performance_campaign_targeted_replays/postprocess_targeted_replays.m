function d=max_common_difference(a,b)
names={'omega_raw_E1','omega_raw_E2','omega_raw_E3','omega_binary_E1','omega_binary_E2','omega_binary_E3'};d=0;
for i=1:numel(names),d=max(d,max(abs(a.(names{i})(:)-b.(names{i})(:))));end
end

function same=numerical_history_equal(a,b)
namesA=sort(fieldnames(a));namesB=sort(fieldnames(b));
same=isequal(namesA,namesB);if ~same,return;end
for i=1:numel(namesA)
    name=namesA{i};
    if strcmp(name,'elapsed_s'),continue;end
    same=same&&isequaln(a.(name),b.(name));
    if ~same,return;end
end
end

function x=first_numeric_field(s,names)
x=NaN;for i=1:numel(names),if isfield(s,names{i})&&isnumeric(s.(names{i}))&&isscalar(s.(names{i})),x=double(s.(names{i}));return;end,end
end

function x=first_text_field(s,names)
x='';for i=1:numel(names),if isfield(s,names{i}),x=char(string(s.(names{i})));return;end,end
end

function xb=binary_exact(x)
x=double(x(:));n=round(0.5*numel(x));[~,ord]=sortrows([-x,(1:numel(x))'],[1 2]);xb=zeros(size(x));xb(ord(1:n))=1;
end

function s=numeric_fingerprint(x)
x=double(x(:));w=(1:numel(x))';s=sprintf('n=%d;sum=%.17g;weighted=%.17g;l2=%.17g',numel(x),sum(x),sum(w.*x),norm(x));
end

